#!/usr/bin/env bash
# Check the input data of the experiments:
#   1. the shipped instance files in data/ decompress to the checksums in data/SHA256SUMS;
#   2. the generator, built from the current source, reproduces every one of them exactly
#      (the experiments generate their instances in memory, so this is the check that the
#      instances they used are the shipped ones), and every planted schedule is feasible under
#      the independent validator;
#   3. the ITC-2007 files in data-ctt/, if present, match data-ctt/SHA256SUMS, and
#      data-ctt/equivalence.csv matches them.
set -euo pipefail
cd "$(dirname "$0")/.."
BIN=${BIN:-build/experiments}
if [ ! -x "$BIN" ]; then
  cmake -S . -B build -DCMAKE_BUILD_TYPE=Release
  cmake --build build
fi
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

echo "1. shipped instance files"
grep -v '^#' data/SHA256SUMS > "$tmp/sums"
for f in data/*.txt.gz; do gunzip -c "$f" > "$tmp/$(basename "$f" .gz)"; done
(cd "$tmp" && sha256sum --quiet -c sums) && echo "   $(grep -c . "$tmp/sums") files match"

echo "2. regenerated by the current generator"
rm -f "$tmp"/*.txt
echo "   $("$BIN" instances --data "$tmp" | sed "s#$tmp#a temporary directory#")"
(cd "$tmp" && sha256sum --quiet -c sums) && echo "   all regenerated files match"
extra=$(cd "$tmp" && ls *.txt | wc -l)
[ "$extra" -eq "$(grep -c . "$tmp/sums")" ] || { echo "   regenerated $extra files, expected $(grep -c . "$tmp/sums")"; exit 1; }

echo "3. ITC-2007 files"
if compgen -G "data-ctt/comp*.ctt" > /dev/null; then
  (cd data-ctt && sha256sum --quiet -c SHA256SUMS) && echo "   21 files match SHA256SUMS"
  out=$(python3 scripts/ctt_equivalence.py data-ctt --check)
  echo "   ${out%%$'\n'*}"
else
  echo "   not present (third-party; see data-ctt/README.md) -- skipped"
fi
echo "input data check passed"
